"""
34_function_class_example.py

このスクリプトでは、Python における関数定義（def）とクラスの基本的な使い方を紹介します。
簡単な挨拶関数と、名前と鳴き声を持つDogクラスを定義し、それらを利用してメッセージを
表示します。各行にコメントを付け、関数やクラスの構造が理解しやすいようにしています。
"""

# ---------- 関数定義の例 ----------
def greet(name):  # nameを引数に取り、挨拶文を返す関数を定義します
    """引数で指定された名前に対して挨拶を返します。"""  # 関数の説明を記述します
    return f"こんにちは、{name} さん"  # f文字列を使って挨拶文を作成し返します

# 関数を呼び出して結果を表示します
message = greet("太郎")  # greet関数に"太郎"を渡して挨拶文を取得します
print(message)  # 関数の戻り値を表示します

# ---------- クラス定義の例 ----------
class Dog:  # 犬を表すクラスを定義します
    """犬の名前と鳴き声を管理する簡単なクラスです。"""  # クラスの説明

    def __init__(self, name, bark_sound):  # コンストラクタ: オブジェクト生成時に呼び出されます
        self.name = name  # インスタンスの名前属性に引数nameを保存します
        self.bark_sound = bark_sound  # インスタンスの鳴き声属性に引数bark_soundを保存します

    def bark(self):  # 犬が鳴くメソッドを定義します
        """犬の鳴き声を表す文字列を返します。"""  # メソッドの説明
        return f"{self.name} が {self.bark_sound} と鳴きました"  # 名前と鳴き声を組み合わせて返します

# クラスを使ってインスタンスを生成し、メソッドを呼び出します
dog = Dog("ポチ", "ワンワン")  # Dogクラスのインスタンスを作成します
print(dog.bark())  # barkメソッドを呼び出して鳴き声を表示します