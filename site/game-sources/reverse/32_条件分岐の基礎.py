# coding: utf-8
"""
32_conditionals_example.py

このスクリプトでは、条件分岐（if/elif/else）の基本的な使い方を示します。ランダムに生成
された整数の値に応じて異なるメッセージを表示する簡単な例です。すべての行にコメントを
付けているので、条件分岐の流れを追いやすくなっています。
"""

import random  # randomモジュールを読み込んで乱数を生成できるようにします

# 乱数を生成します。0から2までの整数をランダムに選びます
value = random.randint(0, 2)  # randint(a, b) はa以上b以下の整数を返します

# 条件分岐の開始
if value == 0:  # 変数valueが0の場合の処理
    message = "値は0です"  # 代入するメッセージを定義します
elif value == 1:  # 変数valueが0ではない場合もし変数valueが1の場合の処理
    message = "値は0ではありませんでした、値は1です"  # 代入するメッセージを定義します
else:  # 上記の条件に当てはまらない場合（この場合は2）の処理
    message = "値は2です"  # 代入するメッセージを定義します

# 結果を表示します
print(f"生成された値: {value}")  # f文字列で数値を埋め込んで出力します
print(message)  # 条件によって設定されたメッセージを表示します